def style():
    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 9.5, "axes.spines.top": False,
        "axes.spines.right": False, "axes.grid": True, "grid.alpha": 0.25,
        "figure.dpi": 140, "savefig.dpi": 300, "savefig.bbox": "tight",
        "legend.frameon": False,
    })


def save(fig, out, name):
    fig.savefig(out / f"{name}.png")
    fig.savefig(out / f"{name}.pdf")
    plt.close(fig)


# ---------------------------------------------------------------- loading
def load_runs(runs_dir):
    """Return {group: {seed: DataFrame}} from <runs>/<name>_seedN/*/metrics.csv."""
    groups = defaultdict(dict)
    for path in sorted(runs_dir.glob("*/*/metrics.csv")):
        name = path.parents[1].name
        if not (path.parents[1] / "done").exists():
            continue
        m = re.match(r"(.+)_seed(\d+)$", name)
        df = pd.read_csv(path).sort_values("Train_EnvstepsSoFar")
        groups[m.group(1)][int(m.group(2))] = df
    return groups


def final(groups, g, col="Eval_AverageReturn"):
    vals = np.array([df[col].iloc[-1] for _, df in sorted(groups.get(g, {}).items())])
    return vals


def stat(groups, g, col="Eval_AverageReturn"):
    v = final(groups, g, col)
    if len(v) == 0:
        return dict(mean=float("nan"), std=float("nan"), n=0, values=[])
    return dict(mean=float(v.mean()), std=float(v.std()), n=int(len(v)), values=v.tolist())


def curve(groups, g, col):
    runs = list(groups[g].values())
    steps = runs[0]["Train_EnvstepsSoFar"].to_numpy()
    n = min(len(r) for r in runs)
    ys = np.stack([r[col].to_numpy()[:n] for r in runs])
    return steps[:n], ys.mean(0), ys.std(0)


def plot_curve(ax, groups, g, col, color, label, ls="-"):
    if g not in groups:
        return
    x, m, s = curve(groups, g, col)
    ax.plot(x / 1e3, m, ls, color=color, lw=1.8, marker="o", ms=3,
            label=f"{label} (n={len(groups[g])})")
    ax.fill_between(x / 1e3, m - s, m + s, color=color, alpha=0.18)


# ---------------------------------------------------------------- exports
def export_autograder(groups, out, best_zeta):
    layout = {
        "P1/1": ("awac_umaze", "awac_umaze_seed{}"),
        "P1/2": ("awac_medium", "awac_medium_maze_seed{}"),
        "P2/1": (f"iql_z{best_zeta}_umaze", "iql_umaze_seed{}"),
        "P2/2": (f"iql_z{best_zeta}_medium", "iql_medium_maze_seed{}"),
    }
    root = out / "submission" / "csv_data"
    for folder, (g, fname) in layout.items():
        d = root / folder
        d.mkdir(parents=True, exist_ok=True)
        for seed, df in sorted(groups.get(g, {}).items()):
            run = fname.format(seed)
            pd.DataFrame({
                "Step": df["Train_EnvstepsSoFar"].astype(int),
                f"{run} - Eval_AverageReturn": df["Eval_AverageReturn"],
            }).to_csv(d / f"{run}.csv", index=False)


def macro_tag(key):
    """'iql_z0.9_umaze' -> 'IqlZAJUmaze' (LaTeX macro names allow letters only)."""
    parts = [re.sub(r"\d", lambda d: "ABCDEFGHIJ"[int(d.group())], p.replace(".", ""))
             for p in key.split("_")]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def write_macros(summary, out):
    def fmt(x, nd=1):
        return "--" if x != x else f"{x:.{nd}f}"

    lines = ["% Auto-generated by analysis/plot_results.py",
             "% Tag = group name in CamelCase, '.' dropped, digits 0-9 -> letters A-J"]
    for key, s in summary["groups"].items():
        tag = macro_tag(key)
        lines.append(f"% {key} -> \\{tag}...")
        for col in ("ret", "max", "succ"):
            if col not in s:
                continue
            nd = 2 if col == "succ" else 1
            mk = tag + {"ret": "", "max": "Max", "succ": "Succ"}[col]
            lines.append(f"\\providecommand{{\\{mk}Mean}}{{--}}")
            lines.append(f"\\renewcommand{{\\{mk}Mean}}{{{fmt(s[col]['mean'], nd)}}}")
            lines.append(f"\\providecommand{{\\{mk}Std}}{{--}}")
            lines.append(f"\\renewcommand{{\\{mk}Std}}{{{fmt(s[col]['std'], nd)}}}")
    lines.append("\\providecommand{\\BestZeta}{0.9}")
    lines.append(f"\\renewcommand{{\\BestZeta}}{{{summary['best_zeta']}}}")
    bz = summary["best_zeta"]
    aliases = {
        "IqlBestUmaze": f"iql_z{bz}_umaze",
        "IqlBestMedium": f"iql_z{bz}_medium",
        "IqlBestStitch": f"iql_z{bz}_stitch",
    }
    for macro, key in aliases.items():
        block = summary["groups"].get(key, {})
        for col, suffix in (("ret", ""), ("max", "Max"), ("succ", "Succ")):
            stats = block.get(col)
            if not stats:
                continue
            nd = 2 if col == "succ" else 1
            mk = macro + suffix
            lines.append(f"\\providecommand{{\\{mk}Mean}}{{--}}")
            lines.append(f"\\renewcommand{{\\{mk}Mean}}{{{fmt(stats['mean'], nd)}}}")
            lines.append(f"\\providecommand{{\\{mk}Std}}{{--}}")
            lines.append(f"\\renewcommand{{\\{mk}Std}}{{{fmt(stats['std'], nd)}}}")
    for k, v in summary["meta"].items():
        lines.append(f"\\providecommand{{\\{k}}}{{--}}")
        lines.append(f"\\renewcommand{{\\{k}}}{{{v}}}")
    (out / "results_macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


# ---------------------------------------------------------------- PointMass helpers
def pointmass_walls():
    """Maze6x6 walls from the env module (gym stubbed if missing)."""
    if importlib.util.find_spec("gym") is None:
        reg = types.ModuleType("gym.envs.registration")
        gym = types.ModuleType("gym")
        gym.Env = object
        gym.spaces = types.SimpleNamespace(Discrete=None, Box=None)
        sys.modules.setdefault("gym", gym)
        sys.modules.setdefault("gym.envs.registration", reg)
    sys.path.insert(0, str(HERE / "code"))
    from cs224r.envs.pointmass.pointmass import WALLS
    return WALLS["Maze6x6"]


def draw_walls(ax, walls):
    w = walls.T
    h, wd = w.shape
    for i, j in zip(*np.where(w)):
        ax.fill_between([j / wd, (j + 1) / wd], i / h, (i + 1) / h, color="#B0B0B0", lw=0)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.set_xticks([])
    ax.set_yticks([])
    ax.set_aspect("equal")
    ax.grid(False)


def dataset_trajs():
    d = np.load(STITCH_DATA)
    obs, rew, done = d["obs"], d["reward"], d["done"]
    trajs, start = [], 0
    for i in range(len(obs)):
        if done[i] or i == len(obs) - 1:
            trajs.append((obs[start:i + 1], float(rew[start:i + 1].sum())))
            start = i + 1
    return trajs


def eval_paths(runs_dir, name):
    paths = sorted(runs_dir.glob(f"{name}/*/eval_paths_last.npz"))
    if not paths:
        return [], []
    z = np.load(paths[0])
    obs = [z[k] for k in sorted((k for k in z.files if k.startswith("obs_")),
                                key=lambda k: int(k.split("_")[1]))]
    return obs, z["returns"]


# ---------------------------------------------------------------- figures
def fig_antmaze(groups, out, best_zeta, col, name, ylabel):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.7), sharey=(col == "Eval_SuccessRate"))
    other = 0.2 if best_zeta != 0.2 else 0.9
    for ax, task, title in zip(axes, ("umaze", "medium"),
                               ("antmaze-umaze-v0", "antmaze-medium-diverse-v2")):
        plot_curve(ax, groups, f"awac_{task}", col, C["awac"], "AWAC (lambda=0.1)")
        plot_curve(ax, groups, f"iql_z{best_zeta}_{task}", col, C["iql"],
                   f"IQL (zeta={best_zeta})")
        plot_curve(ax, groups, f"iql_z{other}_{task}", col, C["iql_low"],
                   f"IQL (zeta={other})", ls="--")
        ax.set_title(title)
        ax.set_xlabel("Gradient steps (x1000)")
    axes[0].set_ylabel(ylabel)
    axes[0].legend(fontsize=7.5, loc="best")
    save(fig, out, name)


def fig_sweep(groups, out, pattern, xs, xlabel, name, title, logx=False, extra=None,
              color=None):
    fig, ax = plt.subplots(figsize=(3.5, 2.6))
    color = C["iql"] if color is None else color
    pts = [(x, stat(groups, pattern.format(x))) for x in xs]
    pts = [(x, s) for x, s in pts if s["n"]]
    if pts:
        x = np.array([p[0] for p in pts], dtype=float)
        m = np.array([p[1]["mean"] for p in pts])
        s = np.array([p[1]["std"] for p in pts])
        ax.errorbar(x, m, yerr=s, color=color, marker="o", capsize=3, lw=1.6)
        for xi, (_, st) in zip(x, pts):
            ax.scatter([xi] * st["n"], st["values"], s=9, color=color, alpha=0.35)
    if extra:
        extra(ax)
    if logx:
        ax.set_xscale("log")
    ax.set_xlabel(xlabel)
    ax.set_ylabel("Final eval return")
    ax.set_title(title, fontsize=9.5)
    save(fig, out, name)


def fig_stitch_bars(groups, out, best_zeta):
    cands = [(f"iql_z{best_zeta}_stitch", f"IQL zeta={best_zeta}", C["iql"]),
             ("awac_stitch", "AWAC", C["awac"])]
    cands += [(f"fbc{p}_stitch", f"F-BC top {p}%" if p < 100 else "BC (all)", C["bc"])
              for p in (1, 10, 25, 50, 100)]
    cands = [c for c in cands if c[0] in groups]
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.7), sharey=True)
    for ax, col, title in zip(axes, ("Eval_AverageReturn", "Eval_MaxReturn"),
                              ("Average eval return", "Max eval return")):
        for i, (g, label, color) in enumerate(cands):
            s = stat(groups, g, col)
            ax.bar(i, s["mean"], yerr=s["std"], color=color, alpha=0.85, capsize=3)
            ax.scatter([i] * s["n"], s["values"], color="k", s=7, zorder=3)
        ax.axhline(DATA_MAX, color="crimson", ls="--", lw=1.2, label="dataset max (-46)")
        ax.axhline(DATA_MEAN, color=C["data"], ls=":", lw=1.2, label="dataset mean (-104)")
        ax.set_xticks(range(len(cands)))
        ax.set_xticklabels([c[1] for c in cands], rotation=35, ha="right", fontsize=7.5)
        ax.set_title(title)
    axes[0].set_ylabel("Return (higher is better)")
    axes[0].legend(fontsize=7.5, loc="lower left")
    save(fig, out, "fig6_stitching_returns")


def fig_stitch_traj(runs_dir, out, best_zeta):
    walls = pointmass_walls()
    trajs = dataset_trajs()
    fig, axes = plt.subplots(1, 3, figsize=(7.4, 2.75))
    rets = np.array([r for _, r in trajs])
    norm = plt.Normalize(rets.min(), rets.max())
    ax = axes[0]
    draw_walls(ax, walls)
    for o, r in trajs:
        ax.plot(o[:, 0], o[:, 1], color=plt.cm.viridis(norm(r)), lw=0.6, alpha=0.55)
    ax.set_title(f"Dataset ({len(trajs)} trajs)", fontsize=9)
    sm = plt.cm.ScalarMappable(norm=norm, cmap="viridis")
    fig.colorbar(sm, ax=ax, fraction=0.046, pad=0.02).set_label("Return", fontsize=8)
    for ax, (name, title, color) in zip(axes[1:], (
            (f"iql_z{best_zeta}_stitch_seed1", f"IQL zeta={best_zeta} (seed 1)", C["iql"]),
            ("fbc10_stitch_seed1", "Filtered BC 10% (seed 1)", C["bc"]))):
        draw_walls(ax, walls)
        paths, returns = eval_paths(runs_dir, name)
        for o in paths:
            ax.plot(o[:, 0], o[:, 1], color=color, lw=0.8, alpha=0.5)
        if len(returns):
            title += f"\nmean {np.mean(returns):.0f}, max {np.max(returns):.0f}"
        ax.set_title(title, fontsize=8.5)
    for ax in axes:
        ax.scatter([0.5 / 6], [0.5 / 6], marker="P", color="red", s=60, zorder=5)
        ax.scatter([1.5 / 6], [5.5 / 6], marker="*", color="gold", ec="k", s=110, zorder=5)
    save(fig, out, "fig7_stitching_trajectories")


def fig_dataset_hist(groups, out, best_zeta):
    trajs = dataset_trajs()
    rets = np.array([r for _, r in trajs])
    fig, ax = plt.subplots(figsize=(3.5, 2.6))
    ax.hist(rets, bins=25, color=C["data"], alpha=0.75)
    thr = np.sort(rets)[::-1][max(1, int(np.ceil(len(rets) * 0.1))) - 1]
    ax.axvline(thr, color=C["bc"], ls="--", lw=1.2, label=f"top-10% cutoff ({thr:.0f})")
    for g, label, color in ((f"iql_z{best_zeta}_stitch", "IQL avg", C["iql"]),
                            ("fbc10_stitch", "F-BC 10% avg", C["bc"])):
        s = stat(groups, g)
        if s["n"]:
            ax.axvline(s["mean"], color=color, lw=2, label=f"{label} ({s['mean']:.0f})")
    ax.set_xlabel("Trajectory return")
    ax.set_ylabel("Count")
    ax.set_title("Stitching dataset return distribution", fontsize=9.5)
    ax.legend(fontsize=7)
    save(fig, out, "fig8_dataset_returns")


def fig_diagnostics(groups, out, best_zeta):
    fig, axes = plt.subplots(1, 3, figsize=(7.4, 2.5))
    specs = [
        (axes[0], "Critic Loss", [("awac_umaze", "AWAC umaze", C["awac"], "-"),
                                  ("awac_medium", "AWAC medium", C["awac"], "--")], "AWAC Q loss"),
        (axes[1], "Critic Q Loss", [(f"iql_z{best_zeta}_umaze", "IQL umaze", C["iql"], "-"),
                                    (f"iql_z{best_zeta}_medium", "IQL medium", C["iql"], "--")],
         "IQL Q loss"),
        (axes[2], "Critic V Loss", [(f"iql_z{best_zeta}_umaze", "IQL umaze", C["iql"], "-"),
                                    (f"iql_z{best_zeta}_medium", "IQL medium", C["iql"], "--")],
         "IQL expectile V loss"),
    ]
    for ax, col, lines, title in specs:
        for g, label, color, ls in lines:
            if g in groups and col in next(iter(groups[g].values())).columns:
                plot_curve(ax, groups, g, col, color, label, ls=ls)
        ax.set_yscale("log")
        ax.set_title(title, fontsize=9)
        ax.set_xlabel("Steps (x1000)")
        ax.legend(fontsize=6.5)
    save(fig, out, "fig9_critic_diagnostics")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--runs", default=str(HERE / "artifacts" / "raw" / "runs"))
    p.add_argument("--out", default=str(HERE / "artifacts"))
    a = p.parse_args()
    runs_dir, out = Path(a.runs), Path(a.out)
    figs = out / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    style()
    groups = load_runs(runs_dir)

    zetas = [z for z in (0.2, 0.9) if f"iql_z{z}_umaze" in groups]
    best_zeta = max(zetas, key=lambda z: stat(groups, f"iql_z{z}_umaze")["mean"]) \
        if zetas else 0.9

    summary = {"best_zeta": best_zeta, "groups": {}, "meta": {}}
    for g in sorted(groups):
        entry = {"ret": stat(groups, g)}
        df0 = next(iter(groups[g].values()))
        if "Eval_MaxReturn" in df0:
            entry["max"] = stat(groups, g, "Eval_MaxReturn")
        if "Eval_SuccessRate" in df0:
            entry["succ"] = stat(groups, g, "Eval_SuccessRate")
        entry["final_step"] = int(df0["Train_EnvstepsSoFar"].iloc[-1])
        summary["groups"][g] = entry
    summary["meta"]["NumRuns"] = sum(len(v) for v in groups.values())
    (out / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    write_macros(summary, out)
    export_autograder(groups, out, best_zeta)

    fig_antmaze(groups, figs, best_zeta, "Eval_AverageReturn", "fig1_antmaze_returns",
                "Eval average return")
    fig_antmaze(groups, figs, best_zeta, "Eval_SuccessRate", "fig2_antmaze_success",
                "Eval success rate")

    fig_sweep(groups, figs, "iql_z{}_umaze", (0.2, 0.5, 0.7, 0.9, 0.95), "Expectile zeta",
              "fig3_expectile_umaze", "IQL expectile sweep (antmaze-umaze)")
    fig_sweep(groups, figs, "iql_z{}_stitch", (0.5, 0.7, 0.8, 0.9, 0.95), "Expectile zeta",
              "fig4_expectile_stitching", "IQL expectile sweep (PointMass stitching)",
              extra=lambda ax: ax.axhline(DATA_MAX, color="crimson", ls="--", lw=1,
                                          label="dataset max") or ax.legend(fontsize=7))

    lam_groups = dict(groups)
    if "awac_umaze" in lam_groups:
        lam_groups["awac_lam0.1_umaze"] = lam_groups["awac_umaze"]
    fig_sweep(lam_groups, figs, "awac_lam{}_umaze", (0.03, 0.1, 0.3, 1.0),
              "AWAC temperature lambda", "fig5_awac_lambda",
              "AWAC temperature sweep (antmaze-umaze)", logx=True, color=C["awac"])
    fig_stitch_bars(groups, figs, best_zeta)
    fig_stitch_traj(runs_dir, figs, best_zeta)
    fig_dataset_hist(groups, figs, best_zeta)
    fig_diagnostics(groups, figs, best_zeta)
    print(json.dumps({g: round(s["ret"]["mean"], 1) for g, s in summary["groups"].items()}))


if __name__ == "__main__":
    main()
