"""Draw Default Project figures and write LaTeX macros from raw metrics.

Usage: python analysis/plot_results.py
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parents[1]
RAW = HERE / "artifacts" / "raw"
FIG = HERE / "artifacts" / "figures"
MACRO = HERE / "reports" / "results_macros.tex"

DIGITS = {str(i): "ABCDEFGHIJ"[i] for i in range(10)}


def style():
    """Matplotlib defaults. Tick and legend text stay in English."""
    plt.rcParams.update({
        "font.family": "DejaVu Sans",
        "font.size": 9.5,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.grid": True,
        "grid.alpha": 0.25,
        "figure.dpi": 140,
        "savefig.dpi": 300,
        "savefig.bbox": "tight",
        "legend.frameon": False,
    })


def save(fig, name):
    """Write png and pdf copies of one figure."""
    FIG.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG / f"{name}.png")
    fig.savefig(FIG / f"{name}.pdf")
    plt.close(fig)


def read_jsonl(path):
    """Load a metrics jsonl file. Missing files yield an empty list."""
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def train_rows(rows, key):
    """Keep rows that record an optimizer step rather than an eval summary."""
    return [row for row in rows if row.get(key) is not None]


def rolling(values, window):
    """Trailing mean. The first points use the available prefix."""
    out = np.empty(len(values), dtype=float)
    acc = 0.0
    for i, value in enumerate(values):
        acc += value
        if i >= window:
            acc -= values[i - window]
        out[i] = acc / min(i + 1, window)
    return out


def macro_name(text):
    """Turn a tag into a LaTeX command name. Digits become A-J."""
    chars = []
    for char in text:
        if char.isdigit():
            chars.append(DIGITS[char])
        elif char.isalpha():
            chars.append(char)
    return "".join(chars)


def write_macros(pairs):
    """Write providecommand/renewcommand pairs. Values are already formatted."""
    MACRO.parent.mkdir(parents=True, exist_ok=True)
    lines = ["% Auto-generated by analysis/plot_results.py. Do not edit."]
    for name, value in pairs:
        lines.append(f"\\providecommand{{\\{name}}}{{--}}")
        lines.append(f"\\renewcommand{{\\{name}}}{{{value}}}")
    MACRO.write_text("\n".join(lines) + "\n", encoding="utf-8")


def plot_sft(sft_rows):
    """Response NLL and learning rate for the Countdown SFT run."""
    rows = train_rows(sft_rows, "train_loss")
    heldout = [row["eval_loss"] for row in sft_rows if row.get("eval_loss") is not None][-1]
    steps = np.array([row["step"] for row in rows])
    loss = np.array([row["train_loss"] for row in rows])
    lr = np.array([row["lr"] for row in rows])
    fig, ax = plt.subplots(figsize=(4.4, 2.8))
    ax.plot(steps, loss, color="#1F4E79", lw=1.4, label="train NLL")
    ax.axhline(heldout, color="#C45911", ls="--", lw=1.0, label=f"held-out NLL {heldout:.3f}")
    ax.set_xlabel("Optimizer step")
    ax.set_ylabel("Response NLL")
    ax.set_ylim(0, 1.6)
    ax2 = ax.twinx()
    ax2.plot(steps, lr * 1e5, color="#7F7F7F", lw=1.0, alpha=0.85)
    ax2.set_ylabel("Learning rate (1e-5)")
    ax2.grid(False)
    ax2.spines["top"].set_visible(False)
    ax.legend(loc="upper right")
    ax.set_title("SFT on searched Countdown expressions")
    save(fig, "fig1_sft_nll")
    return float(rows[0]["train_loss"]), float(rows[-1]["train_loss"])


def plot_preference(pref):
    """IPO and DPO training curves against the reference-policy identity."""
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.9))
    series = [
        ("ipo_b0.1", "IPO $\\beta$=0.1, sum", "#1F4E79"),
        ("ipo_b0.5", "IPO $\\beta$=0.5, sum", "#C45911"),
        ("ipo_mean_b0.1", "IPO $\\beta$=0.1, mean", "#548235"),
    ]
    ax = axes[0]
    for key, label, color in series:
        rows = train_rows(pref[key], "loss")
        ax.plot([r["step"] for r in rows], [r["loss"] for r in rows],
                color=color, lw=1.2, label=label)
    ax.axhline(25.0, color="#1F4E79", ls=":", lw=0.9)
    ax.axhline(1.0, color="#C45911", ls=":", lw=0.9)
    ax.set_title("IPO square loss")
    ax.set_xlabel("Optimizer step")
    ax.set_ylabel("Loss")
    ax.legend(fontsize=7.5)

    ax = axes[1]
    for key, label, color in [
        ("dpo_b0.1", "DPO $\\beta$=0.1, sum", "#1F4E79"),
        ("dpo_mean_b0.1", "DPO $\\beta$=0.1, mean", "#548235"),
    ]:
        rows = train_rows(pref[key], "loss")
        ax.plot([r["step"] for r in rows], [r["loss"] for r in rows],
                color=color, lw=1.2, label=label)
    ax.axhline(np.log(2), color="#7F7F7F", ls=":", lw=0.9, label="log 2")
    ax.set_title("DPO logistic loss")
    ax.set_xlabel("Optimizer step")
    ax.set_ylabel("Loss")
    ax.legend(fontsize=7.5)
    fig.tight_layout()
    save(fig, "fig2_preference_loss")

    fig, ax = plt.subplots(figsize=(4.6, 2.8))
    for key, label, color in [
        ("ipo_b0.1", "IPO 0.1 sum", "#1F4E79"),
        ("ipo_b0.5", "IPO 0.5 sum", "#C45911"),
        ("ipo_mean_b0.1", "IPO 0.1 mean", "#548235"),
        ("dpo_b0.1", "DPO 0.1 sum", "#7030A0"),
        ("dpo_mean_b0.1", "DPO 0.1 mean", "#ED7D31"),
    ]:
        rows = train_rows(pref[key], "acc")
        ax.plot([r["step"] for r in rows], rolling([r["acc"] for r in rows], 8),
                color=color, lw=1.2, label=label)
    ax.axhline(0.5, color="#7F7F7F", ls=":", lw=0.9)
    ax.set_ylim(0, 1)
    ax.set_xlabel("Optimizer step")
    ax.set_ylabel("Preference accuracy (rolling 8)")
    ax.set_title("Chosen vs rejected log-ratio")
    ax.legend(fontsize=7, ncol=2)
    save(fig, "fig3_preference_accuracy")


def plot_rloo(rloo):
    """On-policy exact-match rate under group size and KL ablations."""
    fig, ax = plt.subplots(figsize=(4.8, 2.9))
    specs = [
        ("k8_s0", "K=8, seed 0", "#1F4E79"),
        ("k8_s1", "K=8, seed 1", "#5B9BD5"),
        ("k2_s0", "K=2, seed 0", "#C45911"),
        ("k8_nokl_s0", "K=8, no KL/entropy", "#548235"),
    ]
    if rloo.get("k8_stop_s0"):
        specs.append(("k8_stop_s0", "K=8, stop fixed", "#7030A0"))
    if rloo.get("k8_stop_long"):
        specs.append(("k8_stop_long", "K=8, 120 steps", "#843C0C"))
    for key, label, color in specs:
        rows = rloo.get(key) or []
        if not rows:
            continue
        exact = [row["reward_exact"] for row in rows]
        ax.plot([row["step"] for row in rows], rolling(exact, 5),
                color=color, lw=1.3, label=label)
    ax.set_ylim(0, 0.6)
    ax.set_xlabel("On-policy step")
    ax.set_ylabel("Exact-match rate (rolling 5)")
    ax.set_title("RLOO sampled reward")
    ax.legend(fontsize=7.5)
    save(fig, "fig4_rloo_exact")

    rows = rloo["k8_s0"]
    steps = [row["step"] for row in rows]
    exact = rolling([row["reward_exact"] for row in rows], 5)
    form = rolling([row["reward_format"] for row in rows], 5)
    miss = np.clip(1.0 - exact - form, 0, 1)
    fig, ax = plt.subplots(figsize=(4.6, 2.8))
    ax.stackplot(steps, exact, form, miss,
                 colors=["#548235", "#ED7D31", "#D9D9D9"],
                 labels=["exact (1.0)", "format only (0.1)", "no answer tag"])
    ax.set_ylim(0, 1)
    ax.set_xlabel("On-policy step")
    ax.set_ylabel("Share of samples")
    ax.set_title("K=8 seed 0 reward mix")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.22), ncol=3, fontsize=7.5)
    save(fig, "fig5_rloo_reward_mix")

    fig, ax = plt.subplots(figsize=(4.6, 2.8))
    ax.plot(steps, [row["kl_loss"] for row in rows], color="#1F4E79", lw=1.2, label="token KL")
    ax.plot(steps, [row["entropy"] for row in rows], color="#C45911", lw=1.2, label="token entropy")
    ax.set_xlabel("On-policy step")
    ax.set_ylabel("Nats")
    ax.set_title("K=8 seed 0 regularizers")
    ax.legend()
    save(fig, "fig6_rloo_kl_entropy")


def plot_passk(summary):
    """Grouped pass@k bars. Each series uses the Chen estimator."""
    order = [
        ("base", "Base"),
        ("sft", "SFT"),
        ("ipo", "IPO sum"),
        ("dpo", "DPO sum"),
        ("ipo_mean", "IPO mean"),
        ("rloo_k8", "RLOO K=8"),
        ("rloo_k8_s1", "RLOO K=8 s1"),
        ("rloo_k2", "RLOO K=2"),
        ("rloo_nokl", "RLOO no KL"),
    ]
    if "rloo_stop" in summary:
        order.append(("rloo_stop", "RLOO stop"))
    if "rloo_long" in summary:
        order.append(("rloo_long", "RLOO 120"))
    labels = [label for _, label in order]
    ks = [1, 4, 8]
    colors = ["#1F4E79", "#5B9BD5", "#C45911"]
    x = np.arange(len(order))
    width = 0.24
    fig, ax = plt.subplots(figsize=(7.4, 3.0))
    for i, k in enumerate(ks):
        vals = [summary[key][f"pass@{k}"] for key, _ in order]
        ax.bar(x + (i - 1) * width, vals, width, color=colors[i], label=f"pass@{k}")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=30, ha="right")
    ax.set_ylim(0, 0.75)
    ax.set_ylabel("Unbiased pass@k")
    ax.set_title("Countdown test, 50 prompts")
    ax.legend(ncol=3)
    save(fig, "fig7_passk")


def fmt(value, digits):
    """Format a float for a LaTeX macro."""
    return f"{value:.{digits}f}"


def main():
    """Load raw metrics, draw figures, and export macros."""
    style()
    sft = read_jsonl(RAW / "sft" / "metrics.jsonl")
    pref = {
        name: read_jsonl(RAW / "pref" / name / "metrics.jsonl")
        for name in ["ipo_b0.1", "ipo_b0.5", "ipo_mean_b0.1", "dpo_b0.1", "dpo_mean_b0.1"]
    }
    rloo_names = ["k8_s0", "k8_s1", "k2_s0", "k8_nokl_s0", "k8_stop_s0", "k8_stop_long"]
    rloo = {name: read_jsonl(RAW / "rloo" / name / "metrics.jsonl") for name in rloo_names}

    eval_files = {
        "base": "base_passk.json",
        "sft": "sft_passk.json",
        "ipo": "ipo_b0.1.json",
        "dpo": "dpo_b0.1.json",
        "ipo_mean": "ipo_mean_b0.1.json",
        "dpo_mean": "dpo_mean_b0.1.json",
        "ipo05": "ipo_b0.5.json",
        "rloo_k8": "rloo_k8_s0.json",
        "rloo_k8_s1": "rloo_k8_s1.json",
        "rloo_k2": "rloo_k2_s0.json",
        "rloo_nokl": "rloo_k8_nokl_s0.json",
        "rloo_stop": "rloo_k8_stop_s0.json",
        "rloo_long": "rloo_k8_stop_long.json",
    }
    summary = {}
    for key, filename in eval_files.items():
        path = RAW / "eval" / filename
        if path.exists():
            summary[key] = json.loads(path.read_text(encoding="utf-8"))["summary"]

    start_loss, end_loss = plot_sft(sft)
    plot_preference(pref)
    plot_rloo(rloo)
    plot_passk(summary)

    eval_sft = [row for row in sft if row.get("eval_loss") is not None][-1]
    ipo = train_rows(pref["ipo_b0.1"], "loss")
    ipo_eval = [row for row in pref["ipo_b0.1"] if row.get("eval_loss") is not None][-1]
    dpo = train_rows(pref["dpo_b0.1"], "loss")
    dpo_eval = [row for row in pref["dpo_b0.1"] if row.get("eval_loss") is not None][-1]
    ipo_mean_eval = [row for row in pref["ipo_mean_b0.1"] if row.get("eval_loss") is not None][-1]
    dpo_mean_eval = [row for row in pref["dpo_mean_b0.1"] if row.get("eval_loss") is not None][-1]
    ipo05_eval = [row for row in pref["ipo_b0.5"] if row.get("eval_loss") is not None][-1]
    k8 = rloo["k8_s0"]

    pairs = [
        ("SftLossStart", fmt(start_loss, 3)),
        ("SftLossEnd", fmt(end_loss, 3)),
        ("SftEvalNll", fmt(eval_sft["eval_loss"], 3)),
        ("SftSteps", str(len(train_rows(sft, "train_loss")))),
        ("IpoLossStart", fmt(ipo[0]["loss"], 1)),
        ("IpoLossEnd", fmt(ipo[-1]["loss"], 2)),
        ("IpoEvalLoss", fmt(ipo_eval["eval_loss"], 2)),
        ("IpoEvalAcc", fmt(ipo_eval["eval_acc"], 3)),
        ("DpoLossStart", fmt(dpo[0]["loss"], 3)),
        ("DpoLossEnd", fmt(dpo[-1]["loss"], 3)),
        ("DpoEvalLoss", fmt(dpo_eval["eval_loss"], 3)),
        ("DpoEvalAcc", fmt(dpo_eval["eval_acc"], 3)),
        ("IpoMeanEvalLoss", fmt(ipo_mean_eval["eval_loss"], 2)),
        ("IpoMeanEvalAcc", fmt(ipo_mean_eval["eval_acc"], 3)),
        ("DpoMeanEvalLoss", fmt(dpo_mean_eval["eval_loss"], 3)),
        ("DpoMeanEvalAcc", fmt(dpo_mean_eval["eval_acc"], 3)),
        ("IpoBetaHalfEvalLoss", fmt(ipo05_eval["eval_loss"], 2)),
        ("IpoBetaHalfEvalAcc", fmt(ipo05_eval["eval_acc"], 3)),
        ("RlooKEightExactMean", fmt(float(np.mean([r["reward_exact"] for r in k8])), 3)),
        ("RlooKEightRewardMean", fmt(float(np.mean([r["reward_mean"] for r in k8])), 3)),
    ]
    for key, tag in [
        ("base", "PassBase"),
        ("sft", "PassSft"),
        ("ipo", "PassIpo"),
        ("dpo", "PassDpo"),
        ("ipo_mean", "PassIpoMean"),
        ("dpo_mean", "PassDpoMean"),
        ("ipo05", "PassIpoBetaHalf"),
        ("rloo_k8", "PassRlooKEight"),
        ("rloo_k8_s1", "PassRlooKEightSeedOne"),
        ("rloo_k2", "PassRlooKTwo"),
        ("rloo_nokl", "PassRlooNoKl"),
    ]:
        pairs.append((tag + "One", fmt(summary[key]["pass@1"], 3)))
        pairs.append((tag + "Four", fmt(summary[key]["pass@4"], 3)))
        pairs.append((tag + "Eight", fmt(summary[key]["pass@8"], 3)))
        pairs.append((tag + "N", str(int(summary[key]["num_responses"]))))
    if summary["sft"].get("pass@16") is not None:
        pairs.append(("PassSftSixteen", fmt(summary["sft"]["pass@16"], 3)))
    if "rloo_stop" in summary:
        pairs.append(("PassRlooStopOne", fmt(summary["rloo_stop"]["pass@1"], 3)))
        pairs.append(("PassRlooStopFour", fmt(summary["rloo_stop"]["pass@4"], 3)))
        pairs.append(("PassRlooStopEight", fmt(summary["rloo_stop"]["pass@8"], 3)))
    if rloo.get("k8_stop_s0"):
        stop_rows = rloo["k8_stop_s0"]
        pairs.append(("RlooStopExactMean", fmt(
            float(np.mean([r["reward_exact"] for r in stop_rows])), 3)))
    if "rloo_long" in summary:
        pairs.append(("PassRlooLongOne", fmt(summary["rloo_long"]["pass@1"], 3)))
        pairs.append(("PassRlooLongFour", fmt(summary["rloo_long"]["pass@4"], 3)))
        pairs.append(("PassRlooLongEight", fmt(summary["rloo_long"]["pass@8"], 3)))
    write_macros(pairs)
    print("figures", FIG)
    print("macros", MACRO)


if __name__ == "__main__":
    main()
